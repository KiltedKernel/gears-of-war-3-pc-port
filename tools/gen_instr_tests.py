"""Extract the recompiler's real output for instructions the port added or changed (first use of each in ppc/),
plus the whole recompiled memset, into build/instr_tests/snippets.inc for tests/instr_tests.cpp.
Rerun after tools/recomp.sh: the tests then check what the current recompiler emits."""
import glob, os, re

OPS = ['bdnzt', 'eqv', 'mulhd', 'frsqrte', 'vnor128', 'vsel128', 'vpkuhus128', 'vpkuwus128', 'vpkswss128',
       'vcfpuxws128', 'vpkd3d128', 'fmadd', 'fmadds', 'fnmsubs', 'fmsubs', 'vmaddfp128', 'vnmsubfp128', 'vmaddcfp128']
MEMSET = '82A93150'

found, memset = {}, None
for f in sorted(glob.glob('ppc/ppc_recomp.*.cpp')):
    text = open(f).read()
    if memset is None and f'PPC_FUNC_IMPL(__imp__sub_{MEMSET})' in text:
        start = text.index(f'PPC_FUNC_IMPL(__imp__sub_{MEMSET})')
        end = text.index('\n}\n', start) + 3
        memset = text[start:end].replace(f'PPC_FUNC_IMPL(__imp__sub_{MEMSET})', 'static void T_memset(PPCContext& __restrict ctx, uint8_t* base)')
    lines = text.split('\n')
    for i, l in enumerate(lines):
        m = re.match(r'\t// (\S+) ?(.*)', l)
        if not m or m.group(1) not in OPS or m.group(1) in found: continue
        body = []
        for l2 in lines[i + 1:i + 60]:
            if l2.startswith('\t// ') or re.match(r'loc_[0-9A-F]+:', l2) or l2.startswith('}'): break
            body.append(l2)
        found[m.group(1)] = (m.group(2), body)

missing = [o for o in OPS if o not in found] + ([] if memset else ['memset'])
assert not missing, missing
os.makedirs('build/instr_tests', exist_ok=True)
with open('build/instr_tests/snippets.inc', 'w') as out:
    out.write('// generated by tools/gen_instr_tests.py from ppc/ (the recompiler\'s actual output)\n')
    for kind, typ, n in (('r', 'PPCRegister', 32), ('f', 'PPCRegister', 32), ('v', 'PPCVRegister', 128)):
        out.write(f'static {typ}& Reg_{kind}(PPCContext& ctx, int i)\n{{\n\tswitch (i)\n\t{{\n')
        for i in range(n): out.write(f'\tcase {i}: return ctx.{kind}{i};\n')
        out.write(f'\tdefault: return ctx.{kind}0;\n\t}}\n}}\n')
    for op in OPS:
        operands, body = found[op]
        name = op.replace('.', '_')
        out.write(f'// {op} {operands}\nstatic const char* const kOperands_{name} = "{operands}";\n')
        out.write(f'static bool T_{name}(PPCContext& __restrict ctx, uint8_t* base)\n{{\n\tPPCRegister temp{{}};\n\tPPCVRegister vTemp{{}};\n\tuint32_t ea{{}};\n')
        labels = set(re.findall(r'goto (loc_[0-9A-F]+);', '\n'.join(body)))
        out.write('\n'.join(body) + '\n')
        out.write('\treturn false;\n')   # fell through: branch not taken
        for lab in labels: out.write(f'{lab}:\n\treturn true;\n')
        out.write('}\n\n')
    out.write(memset)
print('extracted', len(found), 'instructions + memset')
