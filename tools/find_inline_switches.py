"""Find jump tables XenonAnalyse missed: `lis rB,hi / addi rB,rB,lo / rlwinm rI,rX,2,0,29 / lwzx rT,rB,rI / mtctr rT / bctr`
(an absolute table of code addresses), with no bounds check next to it (the caller checks the index, e.g. 822FF238:
14-entry table at 822FF254 inline after the bctr, index checked <= 13 by its caller). XenonRecomp then emitted the bctr
as an indirect call to a case label that is no function -> a jump to host address 0.

Table length: consecutive words that are code addresses near the bctr; for a table inline after the bctr it also ends
where the first case starts. Appends the new tables to the switch table file (default label = last case).

usage: find_inline_switches.py default.bin switch_tables.toml"""
import re, struct, sys

BASE = 0x82000000
img = open(sys.argv[1], 'rb').read()
toml_path = sys.argv[2]
toml = open(toml_path).read()
known = {int(m, 16) for m in re.findall(r'base = 0x([0-9A-Fa-f]+)', toml)}

# executable sections from the PE header
pe = struct.unpack_from('<I', img, 0x3C)[0]
nsec = struct.unpack_from('<H', img, pe + 6)[0]
opt = struct.unpack_from('<H', img, pe + 20)[0]
sec = pe + 24 + opt
code = []
for i in range(nsec):
    name, vsize, va, rsize, rptr = struct.unpack_from('<8sIIII', img, sec + i * 40)
    chars = struct.unpack_from('<I', img, sec + i * 40 + 36)[0]
    if chars & 0x20000000:  # IMAGE_SCN_MEM_EXECUTE
        code.append((BASE + va, BASE + va + vsize))
def is_code(a): return any(lo <= a < hi for lo, hi in code)
def word(a): return struct.unpack_from('>I', img, a - BASE)[0]

def field(i, lo, n): return (i >> (31 - lo - n + 1)) & ((1 << n) - 1)
found = []
for lo, hi in code:
    for a in range(lo + 24, hi - 4, 4):
        if word(a) != 0x4E800420:          # bctr
            continue
        m = word(a - 4)                    # mtctr rT = 7C0903A6 | rT<<21
        if m & 0xFC1FFFFF != 0x7C0903A6:
            continue
        rT = field(m, 6, 5)
        x = word(a - 8)                    # lwzx rT,rB,rI: 31/23
        if x >> 26 != 31 or (x >> 1) & 0x3FF != 23 or field(x, 6, 5) != rT:
            continue
        rB, rI = field(x, 11, 5), field(x, 16, 5)
        if rB == 0:
            rB, rI = rI, rB
        # rlwinm rI,rX,2,0,29 and lis/addi rB within the 6 instructions before
        rX = None; hi16 = lo16 = None; lis_at = None
        for b in range(a - 12, a - 40, -4):
            w = word(b)
            if w >> 26 == 21 and field(w, 11, 5) == rI and field(w, 16, 5) == 2 and field(w, 21, 5) == 0 and field(w, 26, 5) == 29:
                rX = field(w, 6, 5)
            elif w >> 26 == 14 and field(w, 6, 5) == rB and field(w, 11, 5) == rB and lo16 is None:   # addi rB,rB,lo
                lo16 = w & 0xFFFF
            elif w >> 26 == 15 and field(w, 6, 5) == rB and field(w, 11, 5) == 0 and hi16 is None:   # lis rB,hi
                hi16 = w & 0xFFFF
                lis_at = b
        # XenonRecomp keys a switch by its first instruction (the lis): the switch is armed there, emitted at the bctr
        if rX is None or hi16 is None or lo16 is None or lis_at in known or a in known:
            continue
        table = ((hi16 << 16) + (lo16 - 0x10000 if lo16 & 0x8000 else lo16)) & 0xFFFFFFFF
        labels = []
        t = table
        while len(labels) < 512:
            if t - BASE + 4 > len(img):
                break
            v = word(t)
            if not is_code(v) or v & 3 or abs(v - a) > 0x10000:
                break
            if table == a + 4 and labels and t >= min(labels):   # inline table ends where the cases start
                break
            labels.append(v)
            t += 4
        if len(labels) < 2:
            continue
        found.append((lis_at, rX, labels))

with open(toml_path, 'a') as f:
    f.write('\n# ---- generated by tools/find_inline_switches.py: absolute tables bounded by the caller ----\n')
    for a, r, labels in found:
        f.write(f'[[switch]]\nbase = 0x{a:08X}\nr = {r}\ndefault = 0x{labels[-1]:08X}\nlabels = [\n')
        for l in labels:
            f.write(f'    0x{l:08X},\n')
        f.write(']\n\n')
print(f'{len(found)} new jump tables')
for a, r, labels in found[:20]:
    print(f'  switch {a:08X} r{r} {len(labels)} cases ({labels[0]:08X}..{labels[-1]:08X})')
