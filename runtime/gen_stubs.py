"""Generate weak logging stubs for every kernel/XAM import the recompiled game references (runtime/import_list.txt).
A real implementation anywhere else (a strong PPC_FUNC(__imp__Name)) replaces the stub at link time."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
names = [l.strip() for l in open(os.path.join(HERE, "import_list.txt")) if l.strip()]
L = ["// GENERATED by runtime/gen_stubs.py - do not edit", '#include "runtime.h"', ""]
for n in names:
    L.append(f'PPC_WEAK_FUNC(__imp__{n}) {{ StubImport("{n}", ctx); }}')
open(os.path.join(HERE, "import_stubs.cpp"), "w").write("\n".join(L) + "\n")
print(len(names), "stubs")
