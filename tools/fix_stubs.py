"""Second pass after fix_boundaries.py: a switch error inside a recompiled function S that starts before a real function
F (.pdata or explicit bound) covering the switch means S is a stub that tail-jumps into F and the analyzer swallowed F.
Add an explicit bound {S, F - S}. usage: fix_stubs.py ppc_dir default.bin functions.toml"""
import bisect, glob, os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ximage
ppc, img_path, ftoml = sys.argv[1], sys.argv[2], sys.argv[3]
img = open(img_path, "rb").read()
BASE = ximage.BASE
PDATA, PDATA_SIZE = ximage.pdata(img)
known = {}
for o in range(PDATA - BASE, PDATA - BASE + PDATA_SIZE, 8):
    b, p = struct.unpack_from(">II", img, o)
    if b: known[b] = ((p >> 8) & 0x3FFFFF) * 4
text = open(ftoml).read()
explicit = {int(a, 16): int(b, 16) for a, b in re.findall(r"address = 0x([0-9A-F]+), size = 0x([0-9A-F]+)", text)}
known.update(explicit)
kstarts = sorted(known)
bad = set()
for f in glob.glob(os.path.join(ppc, "ppc_recomp.*.cpp")):
    fn = None
    for line in open(f):
        if line.startswith("PPC_FUNC_IMPL(__imp__sub_"):
            fn = int(line[len("PPC_FUNC_IMPL(__imp__sub_"):].split(")")[0], 16)
        elif "// ERROR: 0x" in line and fn is not None:
            bad.add(fn)
added = {}
for s in sorted(bad):
    i = bisect.bisect_right(kstarts, s)               # first known function after the bad one's start
    if i < len(kstarts) and s not in known:
        f = kstarts[i]
        if f - s <= 0x400:
            added[s] = f - s
explicit.update(added)
with open(ftoml, "w") as o:
    o.write("# generated by tools/fix_boundaries.py + tools/fix_stubs.py\nfunctions = [\n")
    for b, ln in sorted(explicit.items()):
        o.write(f"    {{ address = 0x{b:08X}, size = 0x{ln:X} }},\n")
    o.write("]\n")
print(f"functions with errors {len(bad)}; stubs bounded {len(added)}: {[(hex(a), hex(b)) for a, b in list(added.items())[:6]]}")
